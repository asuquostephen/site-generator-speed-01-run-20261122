const KEYS = ['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary'];
const LINE_RE = /^([a-z_]+):(?: (.*))?$/;
const DATE_RE = /^(\d{4})-(\d{2})-(\d{2})$/;
const NAME_RE = /^[a-z0-9-]+$/;
const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const TAG_RE = /^[^"[\]]+$/;

function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return m === 4 || m === 6 || m === 9 || m === 11 ? 30 : 31;
}

function stringOf(raw) {
  if (raw.charCodeAt(0) === 34) { // '"'
    if (raw.length < 2 || raw.charCodeAt(raw.length - 1) !== 34) return { error: 'a quoted string is not closed' };
    let out = '';
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out += n;
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out += c;
    }
    return { value: out };
  }
  if (raw.charCodeAt(0) === 91) return { error: 'a bare string opens on [' }; // '['
  return { value: raw };
}

function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = stringOf(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date': {
      const m = DATE_RE.exec(raw);
      const y = m ? Number(m[1]) : 0;
      const mo = m ? Number(m[2]) : 0;
      const d = m ? Number(m[3]) : 0;
      if (!m || y < 1970 || y > 2099 || mo < 1 || mo > 12 || d < 1 || d > daysIn(y, mo)) return { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
      return { value: raw };
    }
    case 'tags': {
      if (!raw.startsWith('[') || !raw.endsWith(']')) return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      if (tags.some((t) => t === '' || !TAG_RE.test(t))) return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout':
      return NAME_RE.test(raw) ? { value: raw } : { error: 'key "layout": not a template name' };
    case 'slug':
      return SLUG_RE.test(raw) && raw.length <= 64 ? { value: raw } : { error: 'key "slug": not a slug' };
    default:
      return { error: `unknown key "${key}"` };
  }
}

function isBlankLine(line) {
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (c !== ' ' && c !== '\t') return false;
  }
  return true;
}

/** Front matter + body, or { error }; scans line boundaries without splitting the body. */
function parseFrontMatter(text) {
  let nl = text.indexOf('\n', 0);
  const firstEnd = nl === -1 ? text.length : nl;
  if (text.slice(0, firstEnd) !== '---') return { error: 'no front matter' };
  let pos = nl === -1 ? text.length : nl + 1;
  let lineNo = 2;
  const data = {};
  while (true) {
    nl = text.indexOf('\n', pos);
    const end = nl === -1 ? text.length : nl;
    const line = text.slice(pos, end);
    if (line === '---') {
      const bodyStart = nl === -1 ? text.length : nl + 1;
      if (!hasOwn(data, 'title')) return { error: 'no title' };
      return { data, body: text.slice(bodyStart) };
    }
    if (!isBlankLine(line) && line.charCodeAt(0) !== 35) { // not blank, not '#...'
      const m = LINE_RE.exec(line);
      if (!m) return { error: `line ${lineNo} is not "key: value"` };
      const key = m[1];
      const raw = (m[2] ?? '').replace(/[ \t]+$/, '');
      if (!KEYS.includes(key)) return { error: `unknown key "${key}"` };
      if (hasOwn(data, key)) return { error: `key "${key}" is given twice` };
      if (raw === '') return { error: `key "${key}" has no value` };
      const v = valueOf(key, raw);
      if ('error' in v) return v;
      data[key] = v.value;
    }
    if (nl === -1) break;
    pos = nl + 1;
    lineNo++;
  }
  return { error: 'the front matter is not closed' };
}

// ---------------------------------------------------------------- markdown

const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);
const WS_RE = /\s/;

function trimST(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line[a] === ' ' || line[a] === '\t')) a++;
  while (b > a && (line[b - 1] === ' ' || line[b - 1] === '\t')) b--;
  return line.slice(a, b);
}

function isLangChar(c) {
  return (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c === '_' || c === '+' || c === '-';
}

/** Fence-open language, or null. Line of ``` + optional language + spaces/tabs only. */
function fenceLang(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return null;
  let j = 3;
  while (j < line.length && isLangChar(line[j])) j++;
  for (let k = j; k < line.length; k++) {
    if (line[k] !== ' ' && line[k] !== '\t') return null;
  }
  return line.slice(3, j);
}

/** Fence-close line: ``` + spaces/tabs only. */
function isFenceClose(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return false;
  for (let k = 3; k < line.length; k++) {
    if (line[k] !== ' ' && line[k] !== '\t') return false;
  }
  return true;
}

/** Heading { depth, text } or null. 1-6 #, space/tab, non-empty text (trailing spaces/tabs dropped). */
function headingOf(line) {
  if (line.charCodeAt(0) !== 35) return null;
  let h = 0;
  while (h < line.length && line.charCodeAt(h) === 35) h++;
  if (h === 0 || h > 6) return null;
  if (h >= line.length || (line[h] !== ' ' && line[h] !== '\t')) return null;
  let a = h;
  while (a < line.length && (line[a] === ' ' || line[a] === '\t')) a++;
  let b = line.length;
  while (b > a && (line[b - 1] === ' ' || line[b - 1] === '\t')) b--;
  if (b === a) return null;
  return { depth: h, text: line.slice(a, b) };
}

function isHr(line) {
  if (line.length < 3) return false;
  const a = line.charCodeAt(0);
  if (a !== 45 && a !== 42) return false; // '-' or '*'
  if (line.charCodeAt(1) !== a || line.charCodeAt(2) !== a) return false;
  for (let k = 3; k < line.length; k++) {
    if (line[k] !== ' ' && line[k] !== '\t') return false;
  }
  return true;
}

/** Boolean-only paragraph-end check: same verdict as
 *  isBlankLine || fenceLang !== null || headingOf !== null || isHr, but allocates
 *  nothing (headingOf/fenceLang build an object / a slice). Only called for lines
 *  opening on '`', '#', '-', '*', ' ' or '\t' — the only chars those can start with. */
function endsParagraphFast(line) {
  const c0 = line.charCodeAt(0);
  if (c0 === 96) { // '`': fence open — ``` + lang chars + spaces/tabs only
    if (line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return false;
    let k = 3;
    while (k < line.length && isLangChar(line[k])) k++;
    for (; k < line.length; k++) {
      if (line[k] !== ' ' && line[k] !== '\t') return false;
    }
    return true;
  }
  if (c0 === 35) { // '#': heading — 1-6 '#', a space/tab, then a non-space/tab char
    let h = 0;
    while (h < line.length && line.charCodeAt(h) === 35) h++;
    if (h > 6 || h >= line.length) return false;
    if (line[h] !== ' ' && line[h] !== '\t') return false;
    for (let k = h + 1; k < line.length; k++) {
      if (line[k] !== ' ' && line[k] !== '\t') return true;
    }
    return false;
  }
  if (c0 === 45 || c0 === 42) return isHr(line); // '-' or '*'
  // ' ' or '\t': only a blank line ends the paragraph
  for (let k = 0; k < line.length; k++) {
    if (line[k] !== ' ' && line[k] !== '\t') return false;
  }
  return true;
}

function findUnescaped(s, what, from) {
  for (let j = from; j <= s.length - what.length; j++) {
    if (s[j] === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

function findSingleStar(s, from) {
  for (let j = from; j < s.length; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (c !== '*') continue;
    if (s[j + 1] === '*') {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

const MARK_SCAN_RE = /[\\`*[]/g;

/** Inline rendering: jump between markdown marks with one combined regex scan
 *  (C++ pass) instead of four indexOf scans per step; plain runs are flushed
 *  through escapeHtml in bulk. The shared regex is safe under recursion: every
 *  exec is immediately preceded by setting lastIndex and its result is consumed
 *  before any nested call. */
function inline(s, env) {
  const out = [];
  let i = 0;
  let run = 0;
  const flush = (to) => { if (to > run) out.push(escapeHtml(s.slice(run, to))); };
  while (i < s.length) {
    MARK_SCAN_RE.lastIndex = i;
    const m = MARK_SCAN_RE.exec(s);
    if (m === null) break;
    i = m.index;
    const c = s[i];
    if (c === '\\' && i + 1 < s.length && ESCAPABLE.has(s[i + 1])) {
      flush(i);
      out.push(escapeHtml(s[i + 1]));
      i += 2;
      run = i;
      continue;
    }
    if (c === '`') {
      const j2 = s.indexOf('`', i + 1);
      if (j2 > i + 1) {
        flush(i);
        out.push('<code>', escapeHtml(s.slice(i + 1, j2)), '</code>');
        i = j2 + 1;
        run = i;
      } else i++;
      continue;
    }
    if (c === '*') {
      if (s[i + 1] === '*') {
        const j2 = findUnescaped(s, '**', i + 2);
        if (j2 > i + 2) {
          flush(i);
          out.push('<strong>', inline(s.slice(i + 2, j2), env), '</strong>');
          i = j2 + 2;
          run = i;
        } else i += 2;
        continue;
      }
      const j2 = findSingleStar(s, i + 1);
      if (j2 > i + 1) {
        flush(i);
        out.push('<em>', inline(s.slice(i + 1, j2), env), '</em>');
        i = j2 + 1;
        run = i;
      } else i++;
      continue;
    }
    if (c === '[') {
      const k2 = findUnescaped(s, ']', i + 1);
      const m = k2 !== -1 && s[k2 + 1] === '(' ? s.indexOf(')', k2 + 2) : -1;
      const target = m === -1 ? '' : s.slice(k2 + 2, m);
      if (target !== '' && !WS_RE.test(target)) {
        flush(i);
        out.push('<a href="', escapeHtml(env.link(target)), '">', inline(s.slice(i + 1, k2), env), '</a>');
        i = m + 1;
        run = i;
        continue;
      }
      i++;
      continue;
    }
    i++;
  }
  flush(s.length);
  return out.join('');
}

/** Fused lex + render: blocks are rendered as they are recognised, no token array. */
function renderMarkdown(src, env, slug) {
  const lines = src.split('\n');
  const n = lines.length;
  const ids = new Set();
  const blocks = [];
  const toc = [];
  let excerpt = null;
  let i = 0;
  while (i < n) {
    const line = lines[i];
    if (isBlankLine(line)) { i++; continue; }
    const lang = fenceLang(line);
    if (lang !== null) {
      const body = [];
      i++;
      while (i < n && !isFenceClose(lines[i])) body.push(lines[i++]);
      i++;
      const cls = lang === '' ? '' : ` class="language-${escapeHtml(lang)}"`;
      const codeParts = [];
      for (let k = 0; k < body.length; k++) codeParts.push(escapeHtml(body[k]), '\n');
      blocks.push(`<pre><code${cls}>${codeParts.join('')}</code></pre>`);
      continue;
    }
    const heading = headingOf(line);
    if (heading !== null) {
      const id = uniqueSlug(slug(heading.text), ids);
      const html = inline(heading.text, env);
      blocks.push(`<h${heading.depth} id="${id}">${html}</h${heading.depth}>`);
      if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html });
      i++;
      continue;
    }
    if (isHr(line)) {
      blocks.push('<hr>');
      i++;
      continue;
    }
    if (line.charCodeAt(0) === 62) { // '>'
      const body = [];
      while (i < n && lines[i].charCodeAt(0) === 62) {
        const l = lines[i++];
        body.push(l.charCodeAt(1) === 32 ? l.slice(2) : l.slice(1));
      }
      const kept = [];
      for (let k = 0; k < body.length; k++) {
        const t = trimST(body[k]);
        if (t !== '') kept.push(t);
      }
      blocks.push(kept.length === 0 ? '<blockquote>\n</blockquote>' : `<blockquote>\n<p>${inline(kept.join('\n'), env)}</p>\n</blockquote>`);
      continue;
    }
    const c0 = line.charCodeAt(0);
    const isBullet = (c0 === 45 || c0 === 42) && line.charCodeAt(1) === 32;
    let orderedStart = -1;
    if (!isBullet) {
      // digits then '. '
      let d = 0;
      while (d < line.length && line.charCodeAt(d) >= 48 && line.charCodeAt(d) <= 57) d++;
      if (d >= 1 && d <= 9 && line.charCodeAt(d) === 46 && line.charCodeAt(d + 1) === 32) orderedStart = Number(line.slice(0, d));
    }
    if (isBullet || orderedStart !== -1) {
      const isOrdered = orderedStart !== -1;
      const items = [];
      while (i < n) {
        const l = lines[i];
        let itemText = null;
        if (isOrdered) {
          let d = 0;
          while (d < l.length && l.charCodeAt(d) >= 48 && l.charCodeAt(d) <= 57) d++;
          if (d >= 1 && d <= 9 && l.charCodeAt(d) === 46 && l.charCodeAt(d + 1) === 32) itemText = l.slice(d + 2);
        } else if ((l.charCodeAt(0) === 45 || l.charCodeAt(0) === 42) && l.charCodeAt(1) === 32) {
          itemText = l.slice(2);
        }
        if (itemText !== null) {
          items.push([trimST(itemText)]);
          i++;
        } else {
          // continuation: two or more spaces then a non-whitespace character
          let sp = 0;
          while (sp < l.length && l.charCodeAt(sp) === 32) sp++;
          if (sp >= 2 && sp < l.length && !isWSCode(l.charCodeAt(sp))) {
            items[items.length - 1].push(trimST(l));
            i++;
          } else break;
        }
      }
      const tag = isOrdered ? 'ol' : 'ul';
      const open = isOrdered && orderedStart !== 1 ? `<ol start="${orderedStart}">` : `<${tag}>`;
      let lis = '';
      for (let k = 0; k < items.length; k++) lis += `<li>${inline(items[k].join('\n'), env)}</li>\n`;
      blocks.push(`${open}\n${lis}</${tag}>`);
      continue;
    }
    // paragraph: only a blank line, fence, heading or break ends it, and those all
    // open on '', '`', '#', '-', '*' or a space/tab, so other lines continue unseen.
    const body = [trimST(line)];
    i++;
    while (i < n) {
      const l = lines[i];
      if (l === '') break;
      const c0 = l.charCodeAt(0);
      if (c0 === 96 || c0 === 35 || c0 === 45 || c0 === 42 || c0 === 32 || c0 === 9) {
        if (endsParagraphFast(l)) break;
      }
      body.push(trimST(l));
      i++;
    }
    const html = inline(body.join('\n'), env);
    if (excerpt === null) excerpt = html;
    blocks.push(`<p>${html}</p>`);
  }
  let html = '';
  for (let k = 0; k < blocks.length; k++) html += blocks[k] + '\n';
  return { html, toc, excerpt: excerpt ?? '' };
}

