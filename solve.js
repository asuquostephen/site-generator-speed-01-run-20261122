// Fast drop-in for makefun-site 1.0.0: run(input) returns byte-for-byte what the
// reference build returns, only faster. Written from the spec (README.md) and the
// reference's observable behaviour. Single-pass design: fused lex+render for
// Markdown, chunk-buffered inline rendering, hand-scanned block starts (no per-line
// regex storm), cached slug/date work, precompiled templates rendered into chunk
// arrays, and include memoisation keyed on the exact values the included template
// can observe. All caches live inside one run() call: nothing is shared between cases.

